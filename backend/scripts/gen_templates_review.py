"""
Write ``docs/templates_review.md``: every agent-v3 reply template, one row per key, the five languages side by side, for proofreading.

    cd backend && python scripts/gen_templates_review.py

The JSON tables in ``app/services/agent_templates/`` are the source of truth; edit them, then re-run this script.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.services import agent_templates  # noqa: E402

ORDER = ("english", "gujarati_roman", "gujarati_script", "hindi_roman", "hindi_devanagari")


def cell(text: str) -> str:
    """Markdown-table-safe cell: pipes escaped, newlines as <br>, placeholders in backticks."""
    import re

    return re.sub(r"(\{\w+\})", r"`\1`", text.replace("|", "\\|").replace("\n", "<br>"))


def main() -> None:
    """Render the review file."""
    tables = agent_templates.load_all()
    count = agent_templates.assert_complete()
    out = [
        "# Agent v3 reply templates — review sheet",
        "",
        f"{count} keys × {len(ORDER)} languages. Generated by `scripts/gen_templates_review.py` from `app/services/agent_templates/*.json` "
        "(edit the JSON, then re-run the script). `{placeholders}` are filled by the engine and must stay.",
        "",
        "Conventions: seller data (product names, colours, categories) is never translated; numbers, ₹ amounts, SKU codes, UPI ids and sizes "
        "(S/M/L/XL) are never translated; Roman Gujarati/Hindi keep the commerce words shop-owners type in English "
        "(order, payment, delivery, cart, UPI, COD); the native-script tables spell those in Gujarati / Devanagari letters.",
        "Key names differ from the brief's examples: `catalog_header` = `browse_header`, `delivery_line` = `card_delivery` / `sum_delivery` + `eta_*`, "
        "`ask_qty` = `q_quantity`, `line_removed` = `ack_removed`, `category_not_found` = `category_not_found` (and `search_none_cats`).",
        "",
        "| key | " + " | ".join(ORDER) + " |",
        "|---|" + "---|" * len(ORDER),
    ]
    for key in tables["english"]:
        out.append(f"| `{key}` | " + " | ".join(cell(tables[lang][key]) for lang in ORDER) + " |")
    target = ROOT / "docs" / "templates_review.md"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {target} ({count} keys)")


if __name__ == "__main__":
    main()
